export function bobrTail(a: {
  lang: Lang;
  beat: Beat;
  expression: string;
  attempt: string | null;
  numbersShown: string[];
  missingIdea: string | null;
  childInput: string | null;
  forbiddenLines: string[];
}): string {
  return [
    `<lang>${a.lang}</lang>`,
    `<beat>${a.beat}</beat>`,
    `<expression>${a.expression}</expression>`,
    `<attempt>${a.attempt ?? ""}</attempt>`,
    `<numbers_shown>${a.numbersShown.join(", ")}</numbers_shown>`,
    ...(a.missingIdea ? [`<missing_idea>${a.missingIdea.replace(/[<>]/g, "")}</missing_idea>`] : []),
    fence("forbidden_lines", `\n${a.forbiddenLines.map((l) => `- ${l.replace(/\s+/g, " ")}`).join("\n")}\n`),
    ...(a.childInput ? [fenceChildInput(a.childInput)] : []),
  ].join("\n");
}
