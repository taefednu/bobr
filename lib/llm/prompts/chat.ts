/** Хвост хода: язык, последние реплики ЭТОГО собеседника (до 6), антиповтор, ввод ребёнка — только в ограждении. */
export function chatTail(a: {
  lang: Lang;
  history: { role: "child" | "ustoz" | "bobr"; text: string }[];
  forbiddenLines: string[];
  childInput: string;
}): string {
  return [
    `<lang>${a.lang}</lang>`,
    `<history>\n${a.history.slice(-6).map((m) => (m.role === "child" ? `child: ${fenceChildInput(m.text)}` : `me: ${fence("my_line", m.text)}`)).join("\n")}\n</history>`,
    fence("forbidden_lines", `\n${a.forbiddenLines.map((l) => `- ${l.replace(/\s+/g, " ")}`).join("\n")}\n`),
    fenceChildInput(a.childInput),
  ].join("\n");
}
