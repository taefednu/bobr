export function judgeTail(a: { lang: Lang; expression: string; attempt: string; checklist: Checklist; explanation: string }): string {
  return [
    `<lang>${a.lang}</lang>`,
    `<task>${a.expression} = ${a.attempt}</task>`,
    `<checklist>\n${a.checklist.ideas.map((i) => `- ${i.id}: ${i.about}`).join("\n")}\n</checklist>`,
    fenceChildInput(a.explanation),
  ].join("\n");
}
